// Generate solid-background logo variants for transactional emails.
//
// Why: iOS Mail's force-invert does NOT touch images, but it inverts the
// surrounding email body. A transparent PNG of a white logo therefore becomes
// invisible the moment the surrounding card is force-inverted to a light
// background. By baking a SOLID white box around the dark-blue logo (and a
// solid navy box around the white logo), we guarantee the logo stays
// readable in BOTH light and dark mode, AND under any client's force-invert.
//
// Outputs (in public/assets/email/):
//   logo-on-white.png      — 600×200, dark logo on solid #ffffff
//   logo-on-white@2x.png   — 1200×400, retina version
//   logo-on-dark.png       — 600×200, white logo on solid #0a1024
//   logo-on-dark@2x.png    — 1200×400, retina version
//
// Also prints base64 strings for each, ready to paste into
// supabase/functions/seed-email-assets/index.ts.
//
// Usage:  npm run emails:logos

import sharp from 'sharp';
import { mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');
const OUT  = path.join(REPO, 'public', 'assets', 'email');
const SRC_BLUE  = path.join(REPO, 'public', 'assets', 'logo-blue.png');
const SRC_WHITE = path.join(REPO, 'public', 'assets', 'logo-white.png');

mkdirSync(OUT, { recursive: true });

async function compose({ src, bg, file, w, h, padRatio = 0.18 }) {
  const padX = Math.round(w * padRatio);
  const padY = Math.round(h * padRatio);
  const innerW = w - padX * 2;
  const innerH = h - padY * 2;

  // Resize the source to fit within (innerW × innerH) preserving aspect.
  const inner = await sharp(src)
    .resize({
      width: innerW,
      height: innerH,
      fit: 'contain',
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toBuffer();

  // Composite over a SOLID-color canvas of (w × h).
  const out = path.join(OUT, file);
  await sharp({
    create: { width: w, height: h, channels: 4, background: bg },
  })
    .composite([{ input: inner, gravity: 'center' }])
    .png({ compressionLevel: 9, palette: false })
    .toFile(out);

  return out;
}

async function main() {
  const targets = [
    { src: SRC_BLUE,  bg: { r: 255, g: 255, b: 255, alpha: 1 }, file: 'logo-on-white.png',     w: 600,  h: 200, var: 'LOGO_ON_WHITE_B64' },
    { src: SRC_BLUE,  bg: { r: 255, g: 255, b: 255, alpha: 1 }, file: 'logo-on-white@2x.png',  w: 1200, h: 400, var: 'LOGO_ON_WHITE_2X_B64' },
    { src: SRC_WHITE, bg: { r:  10, g:  16, b:  36, alpha: 1 }, file: 'logo-on-dark.png',      w: 600,  h: 200, var: 'LOGO_ON_DARK_B64' },
    { src: SRC_WHITE, bg: { r:  10, g:  16, b:  36, alpha: 1 }, file: 'logo-on-dark@2x.png',   w: 1200, h: 400, var: 'LOGO_ON_DARK_2X_B64' },
  ];

  console.log('\n→ Composing logo variants…\n');
  for (const t of targets) {
    const outPath = await compose(t);
    const sizeKB = (readFileSync(outPath).length / 1024).toFixed(1);
    console.log(`  ✓ ${t.file.padEnd(28)}  ${t.w}×${t.h}  ${sizeKB} KB`);
  }

  // Print base64 blobs for seed-email-assets.
  console.log('\n→ Base64 blobs for supabase/functions/seed-email-assets/index.ts:');
  console.log('  (Copy the whole block between the BEGIN and END markers.)\n');
  console.log('// ────── BEGIN AUTOGENERATED LOGO BASE64 ──────');
  for (const t of targets) {
    const buf = readFileSync(path.join(OUT, t.file));
    const b64 = buf.toString('base64');
    console.log(`const ${t.var} = "${b64}";`);
  }
  console.log('// ────── END AUTOGENERATED LOGO BASE64 ──────\n');

  console.log(`Wrote 4 files to ${OUT}\n`);
}

main().catch((err) => {
  console.error('Logo generation failed:', err);
  process.exit(1);
});
